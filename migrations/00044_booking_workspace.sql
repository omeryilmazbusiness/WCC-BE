    ADD COLUMN IF NOT EXISTS pnr             TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS service_type    TEXT NOT NULL DEFAULT 'package',
    ADD COLUMN IF NOT EXISTS supplier_source TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS channel         TEXT NOT NULL DEFAULT 'agent',
    ADD COLUMN IF NOT EXISTS summary         TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS company_name    TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS reissue_count   INT  NOT NULL DEFAULT 0;

ALTER TABLE bookings
    ADD CONSTRAINT bookings_service_type_check
        CHECK (service_type IN ('flight','hotel','package','transfer','visa','tour')),
    ADD CONSTRAINT bookings_supplier_source_check
        CHECK (supplier_source IN ('','duffel','paximum','amadeus','sabre','saadia','nusuk','direct_contract','other')),
    ADD CONSTRAINT bookings_channel_check
        CHECK (channel IN ('b2c_web','b2b_agency','whatsapp_bot','agent')),
    ADD CONSTRAINT bookings_reissue_count_check CHECK (reissue_count >= 0);

CREATE UNIQUE INDEX IF NOT EXISTS idx_bookings_ref_no ON bookings(ref_no);
CREATE INDEX IF NOT EXISTS idx_bookings_pnr ON bookings(upper(pnr)) WHERE pnr <> '';
CREATE INDEX IF NOT EXISTS idx_bookings_hold_open ON bookings(hold_expires_at) WHERE status = 'option_hold';
CREATE INDEX IF NOT EXISTS idx_bookings_branch_channel ON bookings(branch_id, channel, service_type);
CREATE INDEX IF NOT EXISTS idx_bookings_created ON bookings(branch_id, created_at DESC);

ALTER TABLE booking_participants
