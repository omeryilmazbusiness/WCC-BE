    ADD COLUMN IF NOT EXISTS health_ok         BOOLEAN NOT NULL DEFAULT FALSE;

ALTER TABLE booking_participants
    ADD CONSTRAINT booking_participants_gender_check CHECK (gender IN ('','male','female'));

CREATE TABLE IF NOT EXISTS booking_notes (
    id          UUID PRIMARY KEY,
    booking_id  UUID NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    author_id   UUID NOT NULL REFERENCES users(id),
    body        TEXT NOT NULL CHECK (length(body) BETWEEN 1 AND 4000),
    pinned      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_booking_notes_booking ON booking_notes(booking_id, pinned DESC, created_at DESC);

CREATE TABLE IF NOT EXISTS booking_change_requests (
    id               UUID PRIMARY KEY,
    booking_id       UUID NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
    kind             TEXT NOT NULL CHECK (kind IN ('date_change','name_change','route_change','other')),
    details          TEXT NOT NULL CHECK (length(details) BETWEEN 1 AND 2000),
    status           TEXT NOT NULL DEFAULT 'requested' CHECK (status IN ('requested','completed','rejected')),
    requested_by     UUID NOT NULL REFERENCES users(id),
    resolved_by      UUID NULL REFERENCES users(id),
    resolution_note  TEXT NOT NULL DEFAULT '',
    created_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    resolved_at      TIMESTAMPTZ NULL
);

CREATE INDEX IF NOT EXISTS idx_booking_changes_booking ON booking_change_requests(booking_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_booking_changes_open ON booking_change_requests(booking_id) WHERE status = 'requested';

-- Activity feed: events about a booking's children carry booking_id in metadata.
CREATE INDEX IF NOT EXISTS idx_audit_events_booking_ref
    ON audit_events ((metadata->>'booking_id'), created_at DESC)
    WHERE metadata ? 'booking_id';

